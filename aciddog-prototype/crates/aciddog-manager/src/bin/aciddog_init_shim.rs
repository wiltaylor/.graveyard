//! Test shim used by the `scaffolding_smoke` integration tests.
//!
//! Stands in for the real `aciddog` binary in the two flows the
//! scaffolding subprocesses: `aciddog init <target>` and
//! `aciddog daemon --check`. std-only — runs synchronously without a
//! tokio runtime so spawn overhead is negligible.
//!
//! Variant matrix (per ADR-0006 implementation plan):
//!   * `init <target>` (default) — write the canonical init-team
//!     `aciddog.wcl` template into `<target>` and exit 0.
//!   * env `ACIDDOG_INIT_SHIM_VARIANT=missing-webservice` — write a
//!     template with NO `:webservice` automaton block.
//!   * env `ACIDDOG_INIT_SHIM_VARIANT=wrong-socket` — write a template
//!     whose `:webservice` block uses `socket_path = "some/other.sock"`.
//!   * env `ACIDDOG_INIT_SHIM_VARIANT=fail` — write nothing, exit 1
//!     with stderr `"shim: simulated init failure"`.
//!   * `daemon --check` (default) — exit 0.
//!   * env `ACIDDOG_INIT_SHIM_CHECK=missing-flag` — exit 2 with stderr
//!     `"unexpected argument '--check'"`.
//!   * env `ACIDDOG_INIT_SHIM_CHECK=parse-error` — exit 1 with stderr
//!     `"parse error: expected automaton block at line 12"`.
//!
//! Always (when target is determinable on the `init` path): dump the
//! observed env to `<target>/.aciddog/observed-env.txt` so the
//! env-allowlist test can assert on it.

use std::env;
use std::fs;
use std::path::PathBuf;
use std::process::ExitCode;

const STANDARD_TEMPLATE: &str = include_str!("../../../../init-team/aciddog.wcl");

const TEMPLATE_WITHOUT_WEBSERVICE: &str = "\
// Skeleton aciddog team — generated by `aciddog init` (test variant).

ai_core default_core {
  type = :claudeCode
  systemPrompt = <<EOT
    You are a code agent operating in a terminal.
  EOT
}

team default {
  description = \"shim variant: missing-webservice\"
  default_ai_core = \"default_core\"
}

agent setup {
  role = \"team architect\"
  role_description = \"shim variant.\"
  instructions = \"shim variant.\"
  supervisor = true
  sysadmin   = true
}
";

const TEMPLATE_WRONG_SOCKET: &str = "\
// Skeleton aciddog team — generated by `aciddog init` (test variant).

ai_core default_core {
  type = :claudeCode
  systemPrompt = \"shim\"
}

team default {
  description = \"shim variant: wrong-socket\"
  default_ai_core = \"default_core\"
}

automaton local_api {
  type             = :webservice
  role             = \"local control plane\"
  role_description = \"Unix-socket bridge for the aciddog-manager portal and local scripts.\"
  socket_path      = \"some/other.sock\"
  supervisor       = true
  sysadmin         = true
  can_message      = [\"setup\"]
}
";

fn main() -> ExitCode {
    let argv: Vec<String> = env::args().collect();
    if argv.len() < 2 {
        eprintln!("aciddog_init_shim: missing subcommand");
        return ExitCode::from(64);
    }

    match argv[1].as_str() {
        "init" => handle_init(&argv),
        "daemon" if argv.get(2).map(String::as_str) == Some("--check") => handle_check(),
        _ => {
            eprintln!("aciddog_init_shim: unsupported argv: {argv:?}");
            ExitCode::from(64)
        }
    }
}

fn handle_init(argv: &[String]) -> ExitCode {
    let target = match argv.get(2) {
        Some(t) => PathBuf::from(t),
        None => {
            eprintln!("aciddog_init_shim: init requires <target>");
            return ExitCode::from(64);
        }
    };

    let variant = env::var("ACIDDOG_INIT_SHIM_VARIANT").ok();

    if matches!(variant.as_deref(), Some("fail")) {
        eprintln!("shim: simulated init failure");
        return ExitCode::from(1);
    }

    // Always create `.aciddog/` so the env dump has somewhere to land.
    if let Err(e) = fs::create_dir_all(target.join(".aciddog")) {
        eprintln!(
            "aciddog_init_shim: could not create {}: {e}",
            target.join(".aciddog").display()
        );
        return ExitCode::from(74);
    }

    let template_text = match variant.as_deref() {
        Some("missing-webservice") => TEMPLATE_WITHOUT_WEBSERVICE,
        Some("wrong-socket") => TEMPLATE_WRONG_SOCKET,
        _ => STANDARD_TEMPLATE,
    };
    let wcl_path = target.join("aciddog.wcl");
    if let Err(e) = fs::write(&wcl_path, template_text) {
        eprintln!(
            "aciddog_init_shim: could not write {}: {e}",
            wcl_path.display()
        );
        return ExitCode::from(74);
    }

    // Dump observed env (sorted) so tests can assert on the allowlist.
    let mut entries: Vec<(String, String)> = env::vars().collect();
    entries.sort_by(|a, b| a.0.cmp(&b.0));
    let mut dump = String::new();
    for (k, v) in &entries {
        dump.push_str(k);
        dump.push('=');
        dump.push_str(v);
        dump.push('\n');
    }
    let env_path = target.join(".aciddog").join("observed-env.txt");
    if let Err(e) = fs::write(&env_path, dump) {
        eprintln!(
            "aciddog_init_shim: could not write {}: {e}",
            env_path.display()
        );
        return ExitCode::from(74);
    }

    ExitCode::SUCCESS
}

fn handle_check() -> ExitCode {
    match env::var("ACIDDOG_INIT_SHIM_CHECK").ok().as_deref() {
        Some("missing-flag") => {
            eprintln!("unexpected argument '--check'");
            ExitCode::from(2)
        }
        Some("parse-error") => {
            eprintln!("parse error: expected automaton block at line 12");
            ExitCode::from(1)
        }
        _ => ExitCode::SUCCESS,
    }
}
